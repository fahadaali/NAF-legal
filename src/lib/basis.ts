/**
 * التمريرة الأولى في «استدلال نظامي»: مواضعُ الاستدلال من النصّ المرسَل.
 *
 * المسار المعتاد يسترجع بخمسة استعلاماتٍ يكتبها المُخطِّط من **الطلب**، وهو
 * كافٍ لسؤالٍ عن مسألة. والاستدلال مسألته المستندُ كلُّه: مذكرةٌ فيها عشرة
 * دفوع، أو عقدٌ فيه عشرون بنداً — وخمسةُ استعلاماتٍ عنها تُغطّي أبرزها
 * وتترك الباقي بلا سند، فيقرأ المحامي جدولاً ناقصاً لا يعرف أنه ناقص.
 *
 * فهذه الخطوة تقرأ النصّ وتُخرج مواضعه، ثم يُبحث لكلِّ موضعٍ على حدة —
 * والدمج بـRRF في `retrieve` يُسقط المكرّر بين المواضع من تلقائه.
 *
 * وهي على نسق `planner.ts` عمداً: نداءٌ غير متدفّق بجهدٍ منخفض، و JSON
 * يُستخرج بتسامح، واحتياطٌ صامتٌ عند الفشل — مصفوفةٌ فارغة تُعيد المسار إلى
 * `plan.kb_queries`، فتنقص التغطية ولا تنقطع الخدمة.
 */
import { callClaude } from './claude';
import { logUsage, usageFromRaw } from './usage';
import type { Env } from '../types';

/** أقصى ما يُستخرج من مواضع. */
export const MAX_ANCHORS = 8;

/* الثمانية سقفُ زمنٍ لا سقفُ معنى.
   حلقة `retrieve` متسلسلة وفيها تضمينُ استعلامٍ لكل دورة، فاثنا عشر موضعاً
   اثنتا عشرة رحلةً متتابعة قبل أن تبدأ أوّل كلمة. والثمانية تُبقي الانتظار
   في حدوده، وتكفي أبرز ما في مذكرةٍ أو عقد. */

/** سقفُ ما يُقرأ من النصّ — نفسُ سقف الملف الواحد في `routes/chat.ts`. */
const ANCHOR_INPUT_MAX = 200_000;

/**
 * أقصر نصٍّ تستحقّ عليه التمريرة الأولى.
 *
 * كلُّ دورٍ في محادثة الاستدلال نوعُه `legal_basis` — بما فيه «وضّح الموضع
 * الثالث». فاستخراجُ المواضع من سؤال متابعةٍ قصير ينفق نداءً على ما لا
 * مواضع فيه، ويردّ استعلاماتٍ عن سؤالٍ لا عن مستند. ودون هذا الحدّ يمضي
 * الدور على مسار المُخطِّط المعتاد — وهو الصواب لسؤالٍ عن موضعٍ بعينه.
 */
export const BASIS_MIN_CHARS = 800;

/** عدد المقاطع المسترجَعة لكل موضع. */
export const BASIS_PER_ANCHOR = 4;

export interface BasisAnchor {
  /** اقتباسٌ من النصّ كما ورد فيه — يدلّ على الموضع ولا يعيد صياغته. */
  quote: string;
  /** ما يُدّعى أو يُلتزَم به في الموضع، بجملةٍ واحدة. */
  claim: string;
  /** استعلامُ بحثٍ في قاعدة الأنظمة عن سند هذا الموضع. */
  query: string;
}

const ANCHORS_SYSTEM = `أنت محلّل نصوص قانونية سعودية. مهمّتك قراءة نصٍّ مكتوب — مذكرة أو لائحة أو عقد — واستخراج المواضع التي تحتاج سنداً نظامياً، وإنتاج JSON فقط دون أي نص إضافي.

أعِد كائن JSON بالشكل:
{
  "anchors": [
    { "quote": "<اقتباس حرفي قصير من النصّ>", "claim": "<ما يُدّعى أو يُلتزَم به في هذا الموضع، جملة واحدة>", "query": "<استعلام بحث عربي عن المادة النظامية التي تحكمه>" }
  ]
}

قواعد:
- quote اقتباسٌ حرفيّ من النصّ المرسَل لا يتجاوز ٢٥ كلمة. لا تُعِد صياغته ولا تُلخّصه.
- query يُكتب بألفاظ الأنظمة لا بألفاظ النصّ: «فسخ عقد الإيجار للإخلال بالالتزام» لا «إنهاء العقد حسب البند الخامس». واذكر اسم النظام المتوقَّع إن كان بيّناً.
- ${MAX_ANCHORS} مواضع على الأكثر. إن زادت فاختر أشدّها أثراً: ما يترتّب عليه حقٌّ أو التزام أو ميعاد أو جزاء — لا الديباجة ولا التعريفات ولا العبارات الإنشائية.
- موضعٌ واحد لكل مسألة. ولا تُفرِد للمسألة الواحدة موضعين لاختلاف صياغتها في النصّ.
- لا تُجب عن المسألة، ولا تذكر أرقام مواد، ولا تُقيّم ما كُتب. هذه خطوةُ تحديد المواضع وحدها.
- إن لم يكن المُرسَل مستنداً قانونياً، أو خلا مما يحتاج سنداً، فأعِد {"anchors": []}.`;

/**
 * مواضع الاستدلال في النصّ، أو مصفوفة فارغة إن تعذّر الاستخراج.
 *
 * ولا ترمي: من يناديها يمضي بما رجع، والفارغ يعني «امضِ على المسار المعتاد».
 */
export async function extractAnchors(env: Env, text: string, userId?: string): Promise<BasisAnchor[]> {
  const source = text.trim().slice(0, ANCHOR_INPUT_MAX);
  if (source.length < BASIS_MIN_CHARS) return [];

  try {
    const { text: out, raw } = await callClaude(env, {
      model: env.PLANNER_MODEL,
      system: ANCHORS_SYSTEM,
      // تحديدُ مواضعَ لا اجتهادٌ فيها، وهو على مسار كل دورِ استدلال:
      // `low` يكفيه ويقصّر الانتظار قبل أن يبدأ البحث.
      effort: 'low',
      max_tokens: 4096,
      messages: [{ role: 'user', content: source }],
    });
    await logUsage(env, { userId, kind: 'anchors', model: env.PLANNER_MODEL, ...usageFromRaw(raw) });
    return normalize(extractJson(out));
  } catch (e) {
    // ويُسجَّل السبب: بلا سطرٍ هنا يبدو جدولٌ ناقص التغطية جدولاً عادياً،
    // ولا يبقى أثرٌ يقول إن التمريرة الأولى لم تقع أصلاً.
    console.error('anchor extraction failed:', e instanceof Error ? e.message : e);
    return [];
  }
}

function extractJson(text: string): { anchors?: unknown } {
  const match = text.match(/\{[\s\S]*\}/);
  if (!match) return {};
  try {
    return JSON.parse(match[0]);
  } catch {
    return {};
  }
}

function normalize(parsed: { anchors?: unknown }): BasisAnchor[] {
  if (!Array.isArray(parsed.anchors)) return [];
  const out: BasisAnchor[] = [];
  for (const a of parsed.anchors) {
    const quote = str(a?.quote);
    const claim = str(a?.claim);
    const query = str(a?.query);
    // الاستعلام هو ما يُبحث به، فموضعٌ بلا استعلام لا يُسترجَع له شيء
    // ويُقحم في الجدول صفّاً فارغاً. والاقتباس هو ما يُعرَض في عموده.
    if (!query || !quote) continue;
    out.push({ quote, claim, query });
    if (out.length >= MAX_ANCHORS) break;
  }
  return out;
}

function str(v: unknown): string {
  return typeof v === 'string' ? v.trim() : '';
}

/**
 * كتلةُ المواضع في البرومبت — بعد السياق النظامي وقبل نصّ الرسالة.
 *
 * الموضع مستخرَجٌ هنا لا في تمريرة التوليد، فلو لم يُدرَج لبناه النموذج من
 * جديد وخالف ما بُحث عنه: صفوفُ الجدول حينئذٍ عن مواضعَ غير التي استُرجعت
 * لها المواد.
 */
export function buildAnchorsBlock(anchors: BasisAnchor[]): string {
  const lines = anchors
    .map((a, i) => `[${i + 1}] ${a.quote}${a.claim ? `\n    المسألة: ${a.claim}` : ''}`)
    .join('\n\n');
  return `\n\n<مواضع_الاستدلال>\nهذه مواضعُ الاستدلال المستخرَجة من النصّ المرسَل، وقد بُحث لكلٍّ منها في قاعدة الأنظمة. اجعل لكلِّ موضعٍ صفّاً في الجدول بترتيبه هنا، ولا تُسقط موضعاً: ما لم تجد له سنداً في السياق النظامي فقل ذلك في صفّه.\n\n${lines}\n</مواضع_الاستدلال>`;
}
