// كان هنا نصفُ منظومة المصادقة المحلية: `hashPassword` و`verifyPassword`
// بـPBKDF2-SHA256، و`signJwt` و`verifyJwt` بـHMAC-SHA256، ومساعداتُ ترميزٍ
// تخدمها. وكلُّها سقطت مع مساراتها في `src/routes/auth.ts`:
//
//   • لا شيء يُجزِّئ كلمة مرور — لا حساب يُنشأ ولا كلمة تُصفَّر في هذه
//     المنصة بعد اليوم.
//   • ولا شيء يتحقّق منها — `‎/login‎` أُسقط.
//   • ولا شيء يوقّع جلسةً محلية ولا يقرؤها — الجلسةُ في المركز،
//     و`lib/auth.ts` يقول بنصّه إنه لا يقرأ جلسةً محلية.
//
// وسقوطها يجعل `JWT_SECRET` سرّاً بلا قارئ. ولم يُنزع من `wrangler.toml`:
// نزعُ سرٍّ من قائمة الإعداد قرارُ تشغيلٍ لا تنظيفُ شيفرة، ووجودُه بلا
// استعمال لا يضرّ. وقد وُسم هناك بأنه كذلك.
//
// وتاريخُ ما سقط في سجلّ Git، ومن أراد إعادةَ دخولٍ محلّي فذاك قرارٌ
// يُتَّخذ ويُسجَّل لا شيفرةٌ تُبعث من رقادها.

export function uuid(): string {
  return crypto.randomUUID();
}
