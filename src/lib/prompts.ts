export function outputStyleInstruction(firmName?: string | null, template?: string | null): string {
  const firm = firmName?.trim() || DEFAULT_FIRM_NAME;
  const text = template?.trim() || DEFAULT_OUTPUT_STYLE;
  return `\n\n${text.split(FIRM_TOKEN).join(firm)}`;
}

