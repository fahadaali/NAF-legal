/* ══ طول الردّ — أربع درجات، ولا واحدة منها تمسّ الدقّة ══
 *
 * الشكوى أن الردود تطول وتتشعّب ويتكرّر فيها بعض النقاط. وأيسرُ علاجٍ يخطر
 * هو خفض الجهد (`effort`) أو سقف الرموز، وكلاهما يشتري القِصَر من الدقّة:
 * الجهد عمقُ التفكير قبل أوّل كلمة، والسقف مشتركٌ بين التفكير والنصّ —
 * التفصيل في كتلة التعليق فوق `ATTEMPTS` في `routes/chat.ts`. فمحامٍ اختار
 * «قصير» ليقرأ أسرع كان يأخذ جواباً أضعف سنداً، وهو آخر ما طلب.
 *
 * فالضبط توجيهٌ وحده: `effort` و`max_tokens` لا يتغيّران بتغيّر الدرجة.
 *
 * والاختصار يقع على الشرح والتحليل، ولا يقع على أركان المستند ولا على
 * الأسانيد — وهو منصوصٌ في كل درجة لأن النموذج بلا نصٍّ يختصر أيسرَ ما
 * يُختصر، وهو الجدول: «قصير» على صحيفة دعوى يقصّر التسبيب ولا يحذف بياناً
 * من بياناتها، وعلى «مراجعة وتدقيق مستند» يقصّر التعليق في كل خانة ولا
 * يُسقط بنداً من الصفوف.
 */
export type ReplyLength = 'short' | 'medium' | 'long' | 'extended';

