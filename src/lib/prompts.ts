/** تعليمة الدرجة المختارة — و«متوسط» لكل قيمة لم تُسجَّل، فالافتراض لا يُترك للصدفة. */
export function lengthInstructionFor(value: string | null | undefined): string {
  return LENGTH_INSTRUCTIONS[value as ReplyLength] ?? LENGTH_INSTRUCTIONS.medium;
}

