// الدخول الموحّد — مسار الاستقبال
//
// يقابل `functions/auth/callback.js` في وثيقة الربط، بصيغة Worker على Hono
// كما يوثّقها README الحزمة. ولا منطق هنا: المبادلة والتحقق والإدراج وفتح
// الجلسة كلها داخل `handleCallback` ولا يُنسخ منها شيء.

import { Hono } from 'hono';
import { handleBackchannelLogout, handleCallback, handleLogout } from 'naf-auth';
import { ssoConfig } from '../lib/sso';
import type { Env, Variables } from '../types';

const app = new Hono<{ Bindings: Env; Variables: Variables }>();

app.get('/callback', (c) => handleCallback(c.req.raw, c.env, ssoConfig(c.env)));

/**
 * الخروج — في الحزمة، ووجهته المركز.
 *
 * كان هنا تحويلٌ إلى `‎/` بعد حذف الجلسة ومسح الكوكي. والحذف والمسح يقعان
 * فعلاً، ولا أثر يراه المستخدم: الجذر محميّ، فيحوّله الوسيط إلى
 * `‎/go/NAF-legal`، وجلسة المركز لم تُمسّ فتُصدر رمزاً جديداً — فيعود
 * الخارجُ إلى شاشته قبل أن يقرأ شيئاً.
 *
 * و`handleLogout` وجهته `‎{issuer}/`، خارج السياج.
 *
 * ويقبل التنقّل ونداء `fetch` معاً، وشكل الردّ يتبع طبيعة الطلب: ٣٠٢ للأوّل
 * لأن المتصفّح يتبعها، و`{ ok, next }` للثاني لأن `fetch` لا يتبع تحويلةً
 * إلى أصل آخر بلا `CORS`.
 *
 * و`POST` وحده — وكان `GET` معه.
 *
 * رابطٌ يُخرج صاحبَه بمجرّد فتحه تكفي صورةٌ في صفحةٍ أجنبية لتشغيله:
 * `<img src="https://…/auth/logout">` يُخرج قارئَها من المنصة بلا علمه،
 * فيفقد ما لم يحفظه. وليس اختطافَ حساب، لكنه فعلٌ يقع بلا قصد صاحبه —
 * وهو ما يمنعه اشتراطُ `POST`: الصور والروابط لا تُرسل إلا `GET`.
 *
 * والواجهة تُرسل نموذجاً بـ`POST` كما تفعل `naf-marketing` و`NAF-Accountant`،
 * فيبقى التنقّل تنقّلاً ويتّبع المتصفّحُ الـ٣٠٢ كما كان.
 *
 * وهو مسجَّل قبل الوسيط، فيعمل لمن انتهت جلسته أصلاً — وحمايتُه كانت تحوّل
 * الخارجَ إلى المركز ليدخل قبل أن يُسمح له بالخروج.
 */
app.post('/logout', (c) => handleLogout(c.req.raw, c.env, ssoConfig(c.env)));

/**
 * إشعار الخروج الخلفي — المركز يُنهي جلسات عضوٍ هنا.
 *
 * الخروج من هذه المنصة محليّ، أمّا الخروج من المركز فهو الباب نفسه: يُنهي
 * جلسات صاحبه في المنصات الخمس. وبلا هذا المسار تبقى جلسته هنا حيّة حتى
 * ينتهي رمزها، فيفتح رابط المنصة بعد خروجه من المركز فيدخل.
 *
 * وهو قبل الوسيط كالخروج، ولسببٍ أقوى: المنادي هو المركز خادماً لخادم، لا
 * متصفّح له جلسة هنا. وحراستُه توقيعُ المركز نفسه — تتحقّق منه الحزمة
 * بمفتاح `JWKS` الذي تعرفه أصلاً.
 */
app.post('/backchannel-logout', (c) =>
  handleBackchannelLogout(c.req.raw, c.env, ssoConfig(c.env)),
);

export default app;
