-- **هذا ملفٌّ يُشغَّل بالطلب لا هجرة.** موضعه `scripts/` عمداً: ما في
-- `migrations/` يُطبَّق مع كل نشر، ومحوٌ يقع مع كل نشرٍ يمحو ما رُفع بعده.
-- يُشغَّل من سير عمل «محو قاعدة المعرفة» وحده، بتأكيدٍ مكتوب ونسخةٍ سابقة.
--
-- والترتيب مقصود: الأبناء قبل الآباء، وما يُحتفظ به يُفكّ ارتباطه قبل أن
-- يجرفه التتالي.

-- ── ١) المدوّنة النظامية ──
-- قرارات المراجعة أوّلاً: قيدٌ يشير إلى مادة محذوفة سجلٌّ عن لا شيء.
DELETE FROM legal_review_audit;

-- النصوص المُزاحة بالتحديثات السابقة.
DELETE FROM legal_chunk_versions;

-- تقارير دفعات الاستيراد.
DELETE FROM legal_imports;

-- المواد. والفهرس اللفظي يتبعها بمحفّز `legal_chunks_ad`: `legal_fts` جدولٌ
-- بمحتوى خارجيّ، فحذفُ الصفّ وحده يترك مدخلته تُطابق ما لا وجود له.
DELETE FROM legal_chunks;

-- وإعادة البناء بعدها تأكيدٌ لا إصلاح: على جدولٍ فارغ تكلفتها لا شيء، وهي
-- تضمن ألا تبقى مدخلةٌ يتيمة لو أخفق محفّزٌ في صفٍّ واحد.
INSERT INTO legal_fts(legal_fts) VALUES ('rebuild');

-- ولا يُعاد ضبط `sqlite_sequence`: `seq` تسلسليّ (AUTOINCREMENT)، وإبقاؤه
-- يجعل ما يُرفع بعد المحو يبدأ من رقمٍ لم يُستعمل. فلو نجا متجهٌ قديم من
-- التفريغ لم يجد صفّاً يقابله — بدل أن يقابل مادةً أخرى فيُنسب نصٌّ إلى غير
-- موضعه، وذاك خطأٌ لا يُرى.

-- ── ٢) الوثائق المرفوعة ──
-- متابعة الأنظمة تبقى: صفوفها مرتبطة بالوثائق بـ`ON DELETE CASCADE`، فيُفكّ
-- الارتباط قبل الحذف وإلا جرفها التتالي معه. ما تتابعه انتهى، وهي باقية.
UPDATE regulation_tracking SET kb_document_id = NULL WHERE kb_document_id IS NOT NULL;

DELETE FROM kb_document_versions;

-- ويشمل الحذف صفوف البذور الستّة (`seed-*`) — أسماء أنظمةٍ مقترَحة بلا محتوى
-- زرعتها الهجرة `0002_seed.sql`. والهجرة لا تُعاد، فمن أرادها بعد المحو
-- يستعيدها بـ`npm run seed` — أمرٌ مذكور في رأس تلك الهجرة نفسها.
DELETE FROM kb_documents;
