-- الاعتماد جملةً — وأثرُه في سجلّ التدقيق.
--
-- المواصفة تمنع «الاعتماد الجماعي بلا قراءة»، وهذا قرارُ المالك بعدها: تحديدٌ
-- صريحٌ لما يراه المراجع على الشاشة، ثم اعتمادُه معاً.
--
-- **والقيد يقول أيَّهما كان.** قرارٌ فُتحت له المادة وقُرئت ألواحها الثلاثة
-- غيرُ قرارٍ وقع على خمسٍ وعشرين دفعةً واحدة — وكلاهما مشروع، وخلطُهما في
-- السجلّ يُفقد التدقيق ما يُدقَّق لأجله. فمن سُئل لاحقاً عن مصدر نصّ مادةٍ في
-- استشارة يعرف لا من اعتمدها ومتى وحدهما، بل كيف.
ALTER TABLE legal_review_audit ADD COLUMN via TEXT;

-- ما وقع قبل هذه الهجرة قرارٌ مفرد: لم يكن للجملة سبيل.
UPDATE legal_review_audit SET via = 'single' WHERE via IS NULL;

CREATE INDEX IF NOT EXISTS idx_review_audit_via ON legal_review_audit(via, at DESC);
