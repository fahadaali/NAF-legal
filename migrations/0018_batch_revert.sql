-- التراجع عن دفعةٍ في نطاق نظام — بصورةٍ كاملة للصفّ قبل الكتابة فوقه.
--
-- **ولمَ لا يكفي `legal_chunk_versions`؟** ذاك سجلُّ إثباتٍ لنصٍّ أُزيح، لا
-- صورةٌ تُستعاد منها المادة: يحفظ ثمانية أعمدة من اثنين وستين — النصَّ والحال
-- والرقم وأداة الإصدار وتواريخها — ولا يحفظ الخطّ الزمني ولا سجلّ التعديلات
-- ولا حالَ الاسترجاع ولا نصَّ التضمين ولا البابَ والفصل. فمن ردّ منه استرجع
-- النصّ وفقد طبقة الإصدار الثالث كلَّها.
--
-- والصورة هنا الصفُّ كما كان، حرفاً بحرف، نصّاً واحداً. لا تُقرأ في استرجاع
-- ولا تُصفّى بها، فلا تُفكَّك أعمدةً: عمودٌ لكل حقلٍ يعني هجرةً جديدة مع كل
-- حقلٍ يُضاف إلى المخطط، وهذا ما يجعل الاستعادة تشيخ مع أوّل دفعةٍ بحقلٍ جديد.
CREATE TABLE IF NOT EXISTS legal_snapshots (
  batch_id   TEXT NOT NULL,
  chunk_id   TEXT NOT NULL,
  law_id     TEXT,
  -- الصفُّ كاملاً قبل أن تكتب الدفعة فوقه. `NULL` لا تقع هنا: ما لا صورة له
  -- في الدفعة مادةٌ **أدرجتها** الدفعة، وتُعرف بغياب صفِّها من هذا الجدول.
  row_json   TEXT NOT NULL,
  at         INTEGER NOT NULL,
  PRIMARY KEY (batch_id, chunk_id)
);
CREATE INDEX IF NOT EXISTS idx_snapshot_law ON legal_snapshots(batch_id, law_id);

-- وقتُ التراجع عن الدفعة — يُقرأ في سجلّ الدفعات فلا تُقرأ دفعةٌ رُدَّت كأنها
-- قائمة. والدفعة لا تُحذف من السجلّ: وقوعُها واقعةٌ، وردُّها واقعةٌ ثانية.
ALTER TABLE legal_imports ADD COLUMN reverted_at INTEGER;
ALTER TABLE legal_imports ADD COLUMN reverted_by TEXT;

