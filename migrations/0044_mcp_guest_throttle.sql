-- سقفُ رمز التحقق للضيف — على الضيف لا على طلب التفويض.
--
-- كان السقفان (خمسة إرسالات وخمس محاولات) على صفّ الطلب في `mcp_guest_codes`،
-- وطلبُ التفويض يُنشئه أيُّ أحدٍ بلا حساب. فطلبٌ جديد يُصفّر العدّادين: إغراقُ
-- بريد الضيف بلا حدّ، وتخمينُ الرمز خمساً بعد خمس حتى يصيب. فالعدّ هنا على
-- الضيف نفسه في نافذةٍ ثابتة، أيّاً كان الطلب الذي جاء منه.
--
-- الهجرات للأمام فقط: ملفٌّ جديد، ولم تُعدَّل 0043.

CREATE TABLE IF NOT EXISTS mcp_guest_throttle (
  guest_id      TEXT PRIMARY KEY,
  -- بداية النافذة (ملّي ثانية). نافذةٌ انقضت تبدأ من الصفر عند أول عدٍّ بعدها.
  window_start  INTEGER NOT NULL,
  sends         INTEGER NOT NULL DEFAULT 0,
  fails         INTEGER NOT NULL DEFAULT 0
);

-- و`mcp_guest_codes.sends` من 0043 لم يعد يُقرأ: العدّ هنا. يبقى العمود ولا
-- يُسقط — هجرةٌ تُسقط عموداً لا رجعة فيها، وقيمتُه الافتراضية تكفي ما يُكتب.
