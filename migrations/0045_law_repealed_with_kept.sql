-- نظامٌ فيه موادُّ «مستبقاة بعد إلغاء النظام» نظامٌ لاغٍ.
--
-- قرارُ صاحب المنصة: «النظام يُعتبر لاغياً، لكن الموادّ المستبقاة لا تُعدّ لاغية.
-- نفرّق بين أصل كون النظام ملغى مع بعض استثناءات في الموادّ».
--
-- وكان ملفُّ استيراد نظام التنفيذ (م/53) يرفع `kept_after_repeal` على سبع عشرة
-- مادةً أبقاها نظام التنفيذ الجديد (م/237)، ولا يرفع `law_repealed` على النظام —
-- لفظُ بطاقته يوم السحب «ساري». فيُعرض بلا وسم «نظام لاغٍ» وموادُّه تقول إنه أُلغي.
--
-- يُرفع العلم هنا على ما في القاعدة اليوم، و`markLawsWithKeptRepealed` في
-- `src/lib/legal.ts` يرفعه بعد كل استيراد فلا يعود.
--
-- **ولا يمسّ حالَ مادة:** شرطُ السريان (`EFFECTIVE_SQL`) لا يقرأ `law_repealed`
-- عمداً، فالمستبقاةُ تبقى نافذةً في البحث والاستشهاد.
--
-- الهجرات للأمام فقط: ملفٌّ جديد، ولم تُعدَّل هجرةٌ سابقة.

UPDATE legal_chunks
SET law_repealed = 1
WHERE law_repealed = 0
  AND law_id IN (SELECT DISTINCT law_id FROM legal_chunks WHERE kept_after_repeal = 1 AND law_id IS NOT NULL);
