-- بصمةُ محتوى المرفق: الملفُّ نفسه إن رُفع ثانيةً أخذ نصَّه المستخرَج فوراً.
--
-- العقدُ نفسه يُرفق في أكثر من محادثة، وصكُّ الحكم يُرفق مع كل لائحة. وكان
-- كلُّ رفعٍ يُعيد القراءة كاملةً — والممسوحُ منها نداءاتٌ إلى النموذج تُدفع
-- كلَّ مرّة وتُنتظر كلَّ مرّة. والبصمةُ SHA-256 للبايتات كما رُفعت، فالملفُّ
-- الذي تغيّر فيه حرفٌ واحد ملفٌّ آخر.
--
-- **والإعادة لصاحب الملف وحده.** البحث بالبصمة مقيَّدٌ بمحادثات المستخدم
-- نفسه في `src/routes/files.ts`: بصمةٌ تطابق ملفَّ غيره لا تكشف أنه رفعه.
--
-- وصفوفُ ما قبل هذا الترحيل بلا بصمة، فلا تُطابَق: تُقرأ مرّةً أخيرة عند رفعها
-- التالي، ثم تُطابَق بعدها.
ALTER TABLE attachments ADD COLUMN content_hash TEXT;
CREATE INDEX IF NOT EXISTS idx_attachments_content_hash ON attachments(content_hash);
