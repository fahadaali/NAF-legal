-- حالُ الاسترجاع لما استُورد قبل أن يكون لها عمود.
--
-- الهجرة 0017 أضافت `retrieval_status` بافتراض `effective` ولم تشتقّها لما كان
-- في القاعدة. فبقيت مادةٌ عليها تعديلٌ لم يُدمج «نافذة» في عمودها، وسدّت الشاشةُ
-- والبرومبت الفجوةَ باشتقاقٍ في كل عرض: «عُدِّلت ولم يُطبَّق تعديلُها» ⇦ تحذير.
--
-- وذلك الاشتقاق هو ما تنهى عنه وثيقة الاستيراد (§3-4): «الغرض ألّا تستنتج
-- المنصة القاعدة من أربعة حقول منطقية». وأثرُه ظاهر: المراجع يعتمد المادة من
-- شاشتها فيُصعّد حالها إلى «نافذ» — ويبقى التحذير معروضاً لأن الاشتقاق لا يقرأ
-- الحال. ومادةٌ قال مُعِدُّ الملف إنها «نافذ» وتعديلُها إخباريّ لم يُدمج لأنه لا
-- يُدمج تُعرض بتحذيرٍ ليس فيها.
--
-- فتُشتقّ الحال هنا مرّةً للمواد التي سبقت عمودها، بالقاعدة نفسها التي يشتقّ
-- بها الاستيراد حين يغيب الحقل — ثم يُعرض التحذير بالحال وحدها.
--
-- **وتُعرف تلك المواد بأن لا خطَّ زمنيّاً لها.** `text_versions` أُضيف في 0017
-- نفسها، والاستيراد يكتبه لكل سطرٍ منذئذٍ ولو نسخةً واحدة. فغيابُه علامةُ ما لم
-- يُرفع بعدها — ولا يمسّ هذا ما قال الملف فيه قولَه.

UPDATE legal_chunks SET retrieval_status = 'repealed'
 WHERE text_versions IS NULL AND retrieval_status = 'effective'
   AND (is_repealed = 1 OR status = 'repealed');

-- ونصُّ التحذير هو المسجَّل في `naf-terms.md` تحت «تنبيهات المادة» حرفاً بحرف.
UPDATE legal_chunks
   SET retrieval_status = 'effective_warning',
       retrieval_warning = COALESCE(retrieval_warning, 'هذه المادة عُدّلت، والنص المعروض هو الأصلي — راجع نص التعديل')
 WHERE text_versions IS NULL AND retrieval_status = 'effective'
   AND has_amendments = 1 AND amendment_applied = 0;
