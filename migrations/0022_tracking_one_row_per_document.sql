-- ============================================================
-- صفٌّ واحد لكل وثيقة في `regulation_tracking` — لا صفٌّ كل ليلة.
--
-- الهجرات للأمام فقط: لا يُعدَّل هذا الملف بعد تشغيله ولو مرة واحدة.
-- ============================================================

-- `runTrackingScan` كان يُدرج صفّاً جديداً بمعرّفٍ جديد في **كل** تشغيل: عشر
-- وثائق كل ليلة، للمتغيّر `needs_review` وللسليم `ok` معاً. فنتج عن ذلك أمران:
--
--   ١) لوحةُ التتبّع تعرض النظام الواحد مكرَّراً بعدد الليالي التي رُصد فيها.
--      و«اعتماد المراجعة» يمحو صفّاً واحداً، والفحص التالي يعيده صفّاً جديداً
--      — فتُقرأ اللوحة كأنها لا تستجيب.
--   ٢) صفوف `ok` لا يقرؤها أحد ولا تُنظَّف: `/admin/tracking` يقرأ
--      `needs_review` وحدها. نموٌّ بلا سقفٍ لجدولٍ لا يُقرأ.
--
-- والحال الصحيحة: للوثيقة صفُّ تتبّعٍ واحد يُحدَّث. فتُجمع الصفوف القائمة
-- على أحدثها، ويُمنع التكرار بقيدٍ على مستوى القاعدة — لا باجتهادٍ في الكود.

-- أحدث صفٍّ لكل وثيقة يبقى، وما قبله يسقط. و`MAX(rowid)` هو آخر ما أُدرج:
-- الترتيب الزمني هو ترتيب الإدراج في هذا الجدول، ولا شيء يعيد كتابة صفّ.
DELETE FROM regulation_tracking
 WHERE rowid NOT IN (SELECT MAX(rowid) FROM regulation_tracking GROUP BY kb_document_id);

-- والقيد بعد التنظيف لا قبله: فريدٌ على جدولٍ فيه مكرَّر يفشل إنشاؤه.
--
-- ويقبل تكرار NULL في SQLite، فصفوفُ التتبّع بلا وثيقة — إن وُجدت من قبل —
-- لا تتزاحم عليه.
CREATE UNIQUE INDEX IF NOT EXISTS idx_tracking_document ON regulation_tracking(kb_document_id);
