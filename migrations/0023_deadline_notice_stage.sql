-- تعليقُ `runDeadlineReminders` يقول: «تُذكِّر قبل 7 و3 و1 يوم ومتأخّرة».
-- والمكتوب غيرُ ذلك: كلُّ موعدٍ `open` استحقاقُه خلال سبعة أيام يُنبَّه عنه
-- **كلَّ يوم** — والحاجز الوحيد عشرون ساعة بين تنبيهين. وموعدٌ فات ولم
-- يُغلَق يبعث إشعاراً داخلياً وبريداً كل ليلةٍ بلا نهاية.
--
-- وشدّةُ الإزعاج تُعلّم المحامي تجاهلَ الشارة، فيضيع التنبيه الذي يهمّ.
--
-- و`notified_at` طابعُ وقتٍ لا يقول **أيَّ** تنبيهٍ أُرسل، فلا يصلح حارساً
-- للمراحل. فيُضاف عمودٌ يحمل المرحلة نفسها:
--
--   d7       بقي سبعة أيام أو أقلّ
--   d3       بقي ثلاثة أو أقلّ
--   d1       بقي يوم أو أقلّ
--   due      يستحقّ اليوم
--   overdue  فات — وتُرسَل مرّةً واحدة ثم لا شيء
--
-- والتنبيه يقع عند **تبدّل** المرحلة وحده، فأقصى ما يُرسَل عن موعدٍ واحد
-- خمسةُ إشعارات على مدى أسبوع، لا سبعةٌ ثم بلا نهاية.
--
-- والعمود يبدأ فارغاً: موعدٌ قائمٌ اليوم يأخذ تنبيهَ مرحلته الحالية مرّةً
-- ثم يسكن. وهو الوضع الصحيح — لا صمتَ عن موعدٍ قريب ولا تكرارَ لما مضى.
