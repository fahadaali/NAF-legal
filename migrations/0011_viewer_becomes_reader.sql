-- المنصة تعرض ثلاثة أدوار وتنفّذ اثنين: `requireAdmin` يفصل المسؤول عن
-- غيره، ولا فحص واحد يفرّق `editor` من `viewer`. فمن حمل «مستخدم (اطّلاع)»
-- يكتب كل شيء — ينشئ المحادثات ويرفع الملفات ويكتب المسوّدات والمواعيد.
--
-- ومع هذه الهجرة يصير الاسم صادقاً: حارسٌ في `lib/auth.ts` يمنع الكتابة
-- عن `viewer`.
--
-- **وهذا السطر يسبق الحارس ولا يتأخّر عنه.** الدور الافتراضي `viewer`،
-- فكلُّ من دخل المنصة ولم يُرقَّ يحمله — وهم عامّة الأعضاء لا قلّتهم.
-- وتشغيلُ الحارس قبل هذا السطر ينزع الكتابة منهم جميعاً في لحظة واحدة:
-- محادثاتٌ مفتوحة تتوقّف، ومسوّداتٌ قيد الكتابة تُردّ بـ٤٠٣.
--
-- فيُرفعون إلى `editor` — وهو ما كانوا يملكونه فعلاً، فلا أحد يفقد شيئاً
-- ولا أحد يُمنح ما لم يكن له. و`viewer` يبقى للمستقبل: يسنده مسؤول المنصة
-- بعد اليوم لمن يريده قارئاً، فيكون قارئاً.
--
-- والمسؤولون لا يُمسّون: الشرط على `viewer` وحده.
UPDATE members SET role = 'editor' WHERE role = 'viewer';
