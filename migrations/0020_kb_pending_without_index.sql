-- وثيقةٌ لم تُضمَّن لا تُوسم «جاهزة».
--
-- `ingestDocument` كان يَسِم الوثيقةَ `ready` بـ`chunk_count = 0` متى كان
-- الفهرس المتجهي غير مهيّأ. والوسمُ كذبٌ لا اختصار: `retrieveKbDocuments`
-- في `lib/rag.ts` يردّ فارغاً بلا الفهرس، فوثيقةٌ «جاهزة» بهذا المعنى لا
-- تبلغ المساعدَ ولا يُستشهد بها — ولا شيء في الشاشة يقول ذلك.
--
-- والصفوف التي كُتبت بذلك الوسم تبقى تحمله بعد إصلاح الشيفرة، فتُردّ هنا
-- إلى `pending` — أي «لم تُضمَّن بعد»، وهي الحال الصادقة. وحين يُهيَّأ
-- الفهرس تلتقطها «تضمين الآن» أو رفعُ نسخةٍ أو «إعادة تضمين».
--
-- **والشرط `chunk_count = 0` هو ما يميّز الكذبة من الصدق.** وثيقةٌ ضُمِّنت
-- فعلاً لها مقطعٌ واحد على الأقل: النصّ الفارغ يُوسم `error` قبل التقطيع،
-- و`chunkText` لا يردّ صفراً على نصٍّ غير فارغ. فالصفر مع `ready` لا يقع
-- إلا من ذلك المسار.
--
-- ولا تُوسّع قائمة `CHECK` بحالٍ خامسة «بانتظار الفهرس»: توسيعُها في SQLite
-- يعيد بناء الجدول كلَّه، والحال تُشتقّ في الشاشة بلا لبس من `pending`
-- مقرونةً بأن الفهرس غير مهيّأ — وهي وحدها التي تعرف ذلك.
UPDATE kb_documents
   SET ingest_status = 'pending'
 WHERE ingest_status = 'ready'
   AND COALESCE(chunk_count, 0) = 0;
