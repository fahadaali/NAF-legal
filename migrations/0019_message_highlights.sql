-- تظليل نصٍّ داخل رسالة — أثرُ قراءةٍ لا أثرُ توليد.
--
-- المحامي يقرأ مذكّرةً مولَّدة فيقف عند جملةٍ يريد أن يعود إليها: مادةٌ
-- استُشهد بها، أو صياغةٌ يريد تغييرها، أو حكمٌ يشكّ فيه. والتظليل هو ما
-- يُبقي ذلك الوقوف بعد أن تُغلق الصفحة.
--
-- **والموضع يُحفَظ بإزاحتين لا بنسخةٍ من النصّ.** النصُّ محفوظٌ في `messages`
-- مرّةً واحدة، وحفظُه ثانيةً هنا يجعل نسختين لجملةٍ واحدة تفترقان أوّل تحرير.
-- والإزاحتان تُقاسان على نصّ الرسالة كما يُعرض — من أوّل حرفٍ فيه — فتُطبَّق
-- على أي عرضٍ له.
--
-- و`text` يُحفَظ مع ذلك، ولا يناقض ما سبق: هو **شاهدٌ لا مصدر**. المسوّدة
-- تُحرَّر وتُعتمد (`draft_versions`)، فتزيح كلمةٌ واحدة كلَّ إزاحةٍ بعدها،
-- ويصير التظليل على جملةٍ لم يظلّلها أحد. فيُقابَل المقتطع بالشاهد عند العرض:
-- ما طابق ظُلِّل، وما خالف سقط صامتاً. وتظليلٌ ذهب أهون من تظليلٍ يقع على
-- الجملة الخطأ في مستندٍ قانوني.
CREATE TABLE IF NOT EXISTS message_highlights (
  id         TEXT PRIMARY KEY,
  message_id TEXT NOT NULL,
  -- صاحبُ التظليل. المحادثة مملوكةٌ لواحد اليوم، والعمود يجعل مشاركتها غداً
  -- لا تخلط تظليل قارئٍ بتظليل آخر.
  user_id    TEXT NOT NULL,
  -- إزاحة البداية والنهاية في نصّ الرسالة المعروض. النهاية حصرية.
  start_off  INTEGER NOT NULL,
  end_off    INTEGER NOT NULL,
  -- المقتطع كما ظُلِّل — شاهدٌ يُقابَل به الموضع، لا نسخةٌ يُقرأ منها.
  text       TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  FOREIGN KEY (message_id) REFERENCES messages(id) ON DELETE CASCADE
);

-- القراءة تقع دائماً برسالةٍ ومرتَّبةً بالموضع: التظليلات تُطبَّق على النصّ
-- بترتيب إزاحاتها، والترتيب في الفهرس يوفّره على كل فتحة محادثة.
CREATE INDEX IF NOT EXISTS idx_message_highlights_message
  ON message_highlights(message_id, start_off);

-- تظليلات قارئٍ بعينه — تُقرأ عند فتح المحادثة، ويُقيَّد بها الحذف.
CREATE INDEX IF NOT EXISTS idx_message_highlights_user
  ON message_highlights(user_id, created_at DESC);
