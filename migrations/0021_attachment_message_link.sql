-- المرفق يُربط برسالته، وحالُ استخراج نصّه تُخزَّن.
--
-- كان المرفق مربوطاً بالمحادثة وحدها، وهذا مصدرُ ثلاث علل في شاشةٍ واحدة:
-- شارتُه تبقى فوق صندوق الكتابة بعد الإرسال فيقرأ صاحبُها أن الملف لم
-- يُرسَل، ونصُّه يُدرَج في **كل** دورٍ تالٍ لأنه لا يعرف أيّ دورٍ هو له،
-- ولا موضع في الشاشة يقول أين ذهب. وهذه الأعمدة تسدّ الثلاث.

-- الرسالة التي أُرسل المرفق معها. و`NULL` حالٌ لها معنى: مرفوعٌ في صندوق
-- الكتابة ولم يُرسَل بعد — وهو ما تعرضه الشاشة شارةً قابلةً للحذف. ولا
-- `NOT NULL` من ثمّ: الرفع يسبق الإرسال بالضرورة.
ALTER TABLE attachments ADD COLUMN message_id TEXT;

-- حالُ استخراج النصّ: `pending` · `ready` · `error`.
--
-- والعمود لازمٌ منذ صار الاستخراج يجري بعد ردّ الرفع لا قبله: `parsed_text`
-- الفارغ لا يفرّق بين «يُقرأ الآن» و«قُرئ فلم يُخرج شيئاً»، والشاشة تحتاج
-- الفرق — الأولى دائرةٌ تدور، والثانية سطرٌ يقول إن نصَّ الملف لا يبلغ
-- المساعد وإن الملف نفسه سليم.
--
-- والافتراض `ready` للقادم من الصفوف القائمة: استخراجُها جرى وقتَ رفعها.
ALTER TABLE attachments ADD COLUMN parse_status TEXT NOT NULL DEFAULT 'ready';

-- سببُ التعثّر كما ورد. يُقرأ في السجلّ لا في الشاشة: نصُّ الخطأ إنجليزيٌّ
-- من وقت التشغيل، والشاشة تعرض الجملة المسجَّلة في `naf-terms.md`.
ALTER TABLE attachments ADD COLUMN parse_error TEXT;

-- القراءة تقع برسالةٍ في كل دور — نصوصُ مرفقات نافذة السجلّ — فالفهرس عليها.
CREATE INDEX IF NOT EXISTS idx_attachments_message ON attachments(message_id);

/* ربطُ ما مضى: كلُّ مرفقٍ إلى أوّل رسالةِ مستخدمٍ تلته.

   وهو ما وقع فعلاً: يرفع الملف ثم يكتب سؤاله ويرسل. والتقريب هنا يعيد
   بناء ما كان يفعله المستخدم، لا ما تخيّلناه.

   ومرفقٌ لا رسالةَ بعده يبقى `NULL` — وهي الحال الصحيحة لا نقصاً في
   الربط: رُفع ولم يُرسَل، فيعود إلى صندوق الكتابة حيث تركه صاحبُه.

   وبلا هذا الربط تخرج مرفقاتُ المحادثات القائمة من سياق المساعد كلَّها
   في أوّل دورٍ بعد النشر: الاختيار صار بالرسالة، ومرفقٌ بلا رسالة لا
   يُختار. */
UPDATE attachments
SET message_id = (
  SELECT m.id FROM messages m
  WHERE m.conversation_id = attachments.conversation_id
    AND m.role = 'user'
    AND m.created_at >= attachments.created_at
  ORDER BY m.created_at ASC
  LIMIT 1
)
WHERE message_id IS NULL;

-- وصفٌّ بلا نصٍّ مستخرَج حالُه `error` لا `ready`: الاستخراج جرى وانتهى إلى
-- لا شيء. والشاشة تقول ذلك ولا تعد بنصٍّ لا وجود له.
UPDATE attachments SET parse_status = 'error'
WHERE parsed_text IS NULL OR parsed_text = '';
