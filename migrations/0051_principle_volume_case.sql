-- المبدأ في مدوّنةٍ متعددة المجلدات، والقضية التي صدر فيها قراره.
--
-- `volume` مجلدُ المدوّنة الذي فيه صفحات المبدأ (`source_pages`). مدوّنةٌ من مجلدٍ
-- واحد تتركه فارغاً. ومدوّنةٌ من مجلدات يبدأ ترقيم صفحات كلٍّ منها من أوّله،
-- فالصفحة بلا مجلدها لا تدلّ على موضع: «ص 58» في أيّ المجلدات الأربعة؟
--
-- وليس هو `ref_json.volume`: ذاك موضعُ القرار في مجلدات القرارات (مدوّنتا العمل)،
-- وهذا موضعُ المبدأ في المدوّنة نفسها.
--
-- `case_json` رقمُ القضية التي صدر فيها القرار ونوعُها كما طُبعا:
-- {"kind": "استئناف" | "دعوى", "no": "Z-33106-2020"}.
-- (IMPORT-RUNBOOK §3-١٤)

ALTER TABLE legal_principles ADD COLUMN volume INTEGER;
ALTER TABLE legal_principles ADD COLUMN case_json TEXT;
