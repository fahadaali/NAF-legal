/* مقابلاتُ المفاتيح المخزَّنة بالعربية — للعرض وحده.
 *
 * **موضعٌ واحد لأن المفتاح يُعرض في أكثر من شاشة.** `doc_type` كان مترجَماً
 * في `LegalLaws` وخاماً في مرشّح `LegalReview`: الجدول يقول «نظام» والقائمة
 * تقول `law` عن الشيء نفسه في التبويب نفسه. وخريطتان لمعنىً واحد تفترقان
 * أوّل نوعٍ يُضاف، فتبقى إحداهما ناقصة بلا أن يلحظ أحد.
 *
 * **والمخزَّن يبقى كما ورد.** المقابلات هنا للعرض؛ التصفية تُطابق ما في ملفّ
 * الاستيراد لا ما نعرضه، فترجمةُ المخزَّن تكسر كلَّ استيرادٍ سابق.
 *
 * **وما لا مقابل له يُعرض بمفتاحه.** لا يُنسب إلى أقرب المسجَّل شكلاً — فيقرأ
 * المحامي «قرار» حيث لا قرار — ولا يُجمع في «أخرى» حيث لا يُرى أبداً. يُرى
 * بلفظه الأجنبي فيُسجَّل في `naf-terms.md` ثم يُضاف هنا.
 */

/**
 * أدوات الإصدار — نوع الوثيقة التي وردت منها المادة.
 * مسجَّلة في `naf-terms.md` §٣ «مصطلحات المحتوى النظامي».
 */
const DOC_TYPES: Record<string, string> = {
  law: 'نظام',
  /* «اللائحة التنفيذية» لا «لائحة»: المجرَّدة مسجَّلة للّائحة القضائية —
     الاعتراضية والاستئنافية — وتسميةُ إحداهما باسم الأخرى خطأٌ مهنيّ لا
     لغويّ، في قاعدةٍ نصفُها مذكرات. */
  regulation: 'اللائحة التنفيذية',
  decision: 'قرار',
  circular: 'تعميم',
};

/** نوعُ الأداة بالعربية. وفارغُه شرطة لا نصٌّ فارغ. */
export function docTypeLabel(t: string | null | undefined): string {
  return t ? (DOC_TYPES[t] ?? t) : '—';
}

/**
 * أنواع عمليات الاستهلاك — ما يُسجَّل مع كل نداء إلى النموذج.
 * مسجَّلة في `naf-terms.md` §١١ «تحليلات الاستهلاك».
 */
const USAGE_KINDS: Record<string, string> = {
  planner: 'التخطيط',
  generation: 'التوليد',
  verify: 'تحقّق الإسناد',
  title: 'صياغة العنوان',
  transcribe: 'التفريغ الصوتي',
};

export function usageKindLabel(k: string | null | undefined): string {
  return k ? (USAGE_KINDS[k] ?? k) : '—';
}

/**
 * أدواتٌ تُنفق على النموذج ولا تُنشئ محادثة، فتقع في عمود النوع مع
 * الاستشارات. ألفاظُها المسجَّلة في `naf-terms.md` §١٠.
 */
const TOOL_TYPES: Record<string, string> = {
  compare: 'مقارنة نسختين',
  deadlines: 'حاسبة المواعيد',
  proofread: 'تدقيق لغوي',
};

/**
 * نوعُ ما أُنفق عليه: استشارةٌ أو أداة.
 *
 * ولا يُستدعى `labelFor` وحده هنا: مقابلُه الافتراضي «استشارة» — وهو صحيح في
 * شاشةٍ تعرض محادثةً بعينها، وكذبٌ في جدولٍ يعدّ الأنواع. فثلاثُ أدواتٍ
 * مختلفة تصير صفّاً واحداً اسمه «استشارة»، والمجموع لا يطابق شيئاً.
 */
export function spendTypeLabel(
  type: string | null | undefined,
  consultationLabel: (t: string) => string | undefined
): string {
  if (!type) return 'بلا نوع';
  return TOOL_TYPES[type] ?? consultationLabel(type) ?? type;
}
