import { useEffect } from 'react';

/**
 * إغلاقُ النافذة بمفتاح الهروب.
 *
 * **موضعٌ واحد لأن النمط كان مكتوباً إحدى عشرة مرّة بثلاثة مستويات اكتمال:**
 * ستُّ نوافذ تسمع `Escape` وخمسٌ لا تسمعه، واثنتان تحملان `role="dialog"`
 * وتسعٌ لا تحملانه. والنافذة التي لا تُغلق بالهروب تُحبِس من فتحها بلوحة
 * المفاتيح: زرُّ الإغلاق قد يكون خارج ترتيب التنقّل أو خلف تمريرة.
 *
 * والمستمِع على `window` لا على العنصر: النافذة قد لا تحمل التركيز — يُفتح
 * الحوار ويبقى التركيز على الزرّ الذي فتحه — فمستمِعٌ على العنصر لا يسمع
 * شيئاً.
 *
 * ويُنظَّف مع تفكيك المكوّن، و`onClose` في قائمة الاعتماديات: دالّةٌ تُبنى
 * في كل رسمٍ تُبقي المستمِع الأوّل معلَّقاً على إغلاقٍ قديم.
 *
 * ولا حبسَ للتركيز داخل النافذة هنا: ذاك سلوكٌ ثانٍ له قراره، وموضعُه
 * مكوّنُ نافذةٍ في السجلّ لا خطّافٌ محلّي.
 *
 * و`onClose` اختيارية: `ClauseLibrary` تُعرض نافذةً حيناً ولوحاً مضمَّناً في
 * تبويب الإدارة حيناً — وللمضمَّن لا إغلاق. فيسكت الخطّاف بدل أن يفرض على
 * المستدعي دالّةً فارغة تُموّه الحال.
 */
export function useModalDismiss(onClose: (() => void) | undefined): void {
  useEffect(() => {
    if (!onClose) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [onClose]);
}

/**
 * سماتُ بطاقة النافذة — تُنشَر على `.modal-card`.
 *
 * `role="dialog"` و`aria-modal` معاً: بدونهما يقرأ قارئُ الشاشة محتوى
 * النافذة امتداداً للصفحة تحتها، فلا يعرف قارئُه أنه دخل حواراً ولا أنّ ما
 * وراءه صار خارج السياق.
 *
 * و`onClick` يوقف الانتشار: النقرُ داخل البطاقة لا يبلغ الحجابَ فيُغلقها.
 */
export const modalCardProps = {
  role: 'dialog',
  'aria-modal': true,
  onClick: (e: { stopPropagation: () => void }) => e.stopPropagation(),
} as const;
