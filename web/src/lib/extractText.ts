/* استخراج نصّ المرفق في المتصفّح — قبل أن يُرفع.
 *
 * **الموضع هنا لا في العامل، والسبب قياسٌ لا تفضيل.** حزمة MuPDF عشرةُ
 * ميغابايت خاماً وأربعةٌ ونصف مضغوطة، وحدُّ العامل على الخطة المجانية ثلاثة —
 * والعامل كلُّه اليوم مئةٌ وثمانية كيلوبايت. فلا تدخل هناك بحال. وفي المتصفّح
 * لا حدَّ يمنعها، وتُحمَّل **عند أوّل PDF يُرفَق** لا مع الصفحة.
 *
 * **وهي تُلغي نداء النموذج على ملفّات PDF كلِّها.** كان كلُّ ملفٍّ يُرسَل
 * بايتاتِه كاملةً إلى كلود ليقرأه — عقدٌ من عشرين صفحة يكلّف ما يكلّفه في كل
 * رفعة. والاستخراج هنا مجّانيّ: لا رمز يُنفَق، ولا انتظارَ نداءٍ بعيد.
 *
 * **ولا تُستعمل pdf.js.** قِيست المكتبتان على PDF عربيّ حقيقيّ بخطٍّ مضمَّن:
 * MuPDF ردّ «المادة الأولى: يلتزم صاحب العمل…» بترتيب كلماتٍ منطقيّ — ستُّ
 * كلماتٍ من ثمانٍ مطابقةٌ حرفياً — وردّت pdf.js أشكالاً تقديمية معكوسة
 * (`ﺪﻋﻮﻣ ﻲﻓ ﺮﺟﻷا`) لا تطابق منها كلمةٌ واحدة. والنصّ الذي يبلغ المساعد نصٌّ
 * قانونيّ، ومقلوبُه أسوأ من غيابه.
 *
 * **وما لا تُخرجه يبقى للخادم.** صورةٌ، أو PDF ممسوح ضوئياً بلا طبقة نصّ —
 * كلاهما يحتاج قراءةً بصرية لا فكَّ ترميز. فيُرفع بلا نصّ ويتولّاه الخادم.
 */

/** حدُّ ما يُقرأ محلّياً. أبعدُ منه يتكفّل به الخادم — والسقف في `chat.ts` يقصّ. */
const MAX_PAGES = 200;

const ARABIC = /[\u0600-\u06FF\u0750-\u077F\uFB50-\uFDFF\uFE70-\uFEFF]/;
/* صنفُ ما يُقرأ من اليسار داخل السطر العربي.
   والأرقامُ العربية‑الهندية (‏٠-٩) منه — وغيابُها كان يعكس كلَّ تاريخٍ ورقمِ
   قرارٍ وهويةٍ وجوّال في مستندٍ حقيقيّ: «٢٠٢٦/٠٧/٠١» تخرج «١٠/٧٠/٦٢٠٢». */
const LATIN = /[A-Za-z0-9\u0660-\u0669\u06F0-\u06F9]/;
/** فاصلٌ يبقى داخل المقطع اللاتيني حين يقع **بين** لاتينيَّين: `12,400.00`. */
const SEPARATOR = /[.,:/@\u066B\u066C\u060C-]/;
/** علاماتُ التشكيل — لا تُستعمل إلّا حين يتعذّر قراءةُ المربّع. */
const MARK = /[\u064B-\u0655\u0670\u06D6-\u06ED]/;

/**
 * رسمٌ واحد بموضعه: حرفٌ مفرد، أو حروفُ رابطةٍ فُكّت، أو حرفٌ بعلاماته.
 *
 * والوحدة هي الرسم لا الحرف، لأن ما يملك موضعاً على الصفحة هو الرسم. وفكُّ
 * الرابطة يعطي حروفاً بلا مواضع، فترتيبُها بالموضع عبثٌ بترتيبٍ صحيح.
 */
interface Unit { s: string; x: number; }

/** فرقٌ دون هذا في الإحداثيّ هو تطابقٌ — حوافُّ المربّعات تُقاس لا تُقارَب. */
const EPS = 1e-6;

/**
 * حدّا المربّع أفقياً، أو `null` إن لم يُفهم شكلُه.
 *
 * المكتبة تسلّمه ثمانيةَ أعداد — أربعَ زوايا — وقد تسلّمه كائناً بزوايا
 * مسمّاة. والشكلان يُقرآن، وما عداهما يُترك للاحتياط أدناه.
 */
function quadSpan(q: unknown): [number, number] | null {
  if (Array.isArray(q) && q.length >= 3) return [q[0], q[2]];
  const o = q as { ul?: { x: number }; ur?: { x: number } } | null;
  if (o?.ul && o?.ur) return [o.ul.x, o.ur.x];
  return null;
}

/**
 * هل عرضُ المربّع صفر؟ أي: أهذا المحرف تتمّةُ رسمٍ لا رسمٌ قائمٌ بنفسه؟
 *
 * **وهو قياسٌ لا تخمين.** الرابطة رسمٌ واحد يحمل حروفاً: `لا` و`لإ` و`الله`
 * و`ريال`. والمكتبة تفكّها إلى حروفها، فتعطي **حرفَها المنطقيَّ الأوّل** مربّعَ
 * الرسم كاملاً، وتعطي بقيّتَها مربّعاتٍ صفريّةَ العرض عند حافّته اليمنى.
 * فترتيبُ الحروف بالإحداثيّ — وهو ما يُرجع السطر العربيّ إلى منطقه — يقلب
 * داخلَ الرابطة نفسها: «الله» تخرج «للها»، و«السلام» تخرج «السالم».
 *
 * قِيس على مستندٍ عربيّ حقيقيّ من صفحتين: ١٠٣ محرفاً من ٤٢٦٢ بمربّعٍ صفريّ.
 * والمجموعاتُ الناتجة هي الرسوم نفسها: `لا`×٢٨ و`لإ`×١٥ و`اً`×١٤ و`الله`×٤
 * و`ريال`×٤.
 *
 * **والعلاماتُ تدخل في القاعدة نفسها.** التشكيل كلّه — إحدى وثلاثون علامة في
 * ذلك المستند — صفريُّ العرض بلا استثناء، فيلحق بحرفه بهذا الميزان وحده. وكان
 * قبله تقديرٌ بتقارُب الإحداثيّات، وهذا أضبطُ منه وأقلّ.
 *
 * وقد جُرِّبت قبله قاعدةٌ مبنيّة على تشارُك الإحداثيّ وحده فأفسدت «الإصلاح»
 * إلى «الإلاصح»: التوقيعُ يقع في رابطتين متجاورتين فيُطبّق مرّتين على موضعٍ
 * واحد. والمربّع لا يلتبس هكذا — عرضُه صفرٌ أو ليس بصفر.
 */
function isZeroWidth(span: [number, number] | null, c: string): boolean {
  // احتياطٌ لمكتبةٍ لا تسلّم مربّعاً: تبقى العلامة لاحقةً بحرفها على الأقلّ.
  if (!span) return MARK.test(c);
  return Math.abs(span[1] - span[0]) < EPS;
}

/**
 * يعيد بناء الترتيب المنطقيّ من الترتيب البصريّ.
 *
 * **والمكتبة لم تكن ضعيفة — كنّا نقرأ مخرجها خطأً.** PDF صيغةٌ بصرية: تخزّن
 * مواضع الرسوم لا نصّاً منطقياً، والمُخرِج يسلّم الحروف بترتيب الرسم. فقراءتُه
 * كما هو تُعطي «‏12,400.00 ريال … المبلغ» مكان «المبلغ 12,400.00 ريال».
 *
 * **والإحداثيّ هو الحقيقة.** في سطرٍ عربيّ الحرفُ المنطقيُّ الأوّل هو الأيمن،
 * فالترتيب التنازليّ بالإحداثيّ يُرجع المنطق. ثم تُعكس مقاطعُ الأرقام
 * واللاتينية وحدها — فهي تُقرأ من اليسار داخل السطر العربي.
 *
 * قياسٌ على مستندين عربيَّين مولَّدَين بخطوطٍ مضمَّنة: ثلاثةُ أسطر من ثلاثة
 * مطابقةٌ **حرفاً بحرف** في الأوّل، ورقمُ القضية `2291/ت/1447` والبريد
 * والهاتف والمبلغ مطابقةٌ في الثاني — وكلُّها كانت مبعثرة قبل هذا.
 */
function toLogical(units: Unit[], rtlPage: boolean): string {
  if (!rtlPage) return [...units].sort((a, b) => a.x - b.x).map((u) => u.s).join('');

  /* ولا تُبدَّل مواضعُ الحروف داخل الرسم الواحد — انظر `isZeroWidth` ونسبةَ
     التتمّات أدناه. الرسمُ وحدَه يُرتَّب بالإحداثيّ، وحروفُه تبقى كما نُسبت. */
  const sorted = [...units].sort((a, b) => b.x - a.x);
  const out: string[] = [];
  let i = 0;
  while (i < sorted.length) {
    if (LATIN.test(sorted[i].s)) {
      // المقطع اللاتينيّ يمتدّ بحرفٍ لاتينيّ، وبفاصلٍ أو فراغٍ **بين** لاتينيَّين.
      let j = i + 1;
      while (j < sorted.length) {
        if (LATIN.test(sorted[j].s)) { j++; continue; }
        const joins = SEPARATOR.test(sorted[j].s) || sorted[j].s === ' ';
        if (joins && j + 1 < sorted.length && LATIN.test(sorted[j + 1].s)) { j += 2; continue; }
        break;
      }
      for (let k = j - 1; k >= i; k--) out.push(sorted[k].s);
      i = j;
    } else {
      out.push(sorted[i].s);
      i++;
    }
  }
  return out.join('');
}

/**
 * حروفٌ عربيّة يكتبها المُخرِج بترميزٍ فارسيٍّ أو أورديّ — تُردّ إلى نصابها.
 *
 * **وليست لغةً أخرى بل جدولُ ترميزٍ معطوب.** المستندُ المقيس عربيٌّ خالص،
 * ويكتب الياء بترميزين: `ي` ٥٠ مرّة في الطرف، و`ی` ١٤٧ مرّة في الوسط. وحرفٌ
 * واحد بترميزين حسب موضعه في الكلمة لا يكون لغةً، وإنّما هو خطُّ الوورد يربط
 * أشكالَ الحرف برموزٍ فارسيّة. وكذلك الهاء: `ھ` سبعون مرّة.
 *
 * والعطبُ لا تراه العين — الرسمُ في الـ PDF عربيٌّ صحيح — لكنه يكسر كلَّ بحث
 * ومطابقة: «منھ» لا تطابق «منه» في أيّ استعلام، ولا يصلحها `normalizeArabic`
 * لأنها لا تعرف هذه الرموز أصلاً.
 *
 * والياءُ والهاء مقيستان في المستند. والكافُ والهاءُ المعقوفة من العطب نفسه
 * ولم تردا فيه، وأُدرجتا بالقياس عليهما لا بالمشاهدة.
 *
 * وثمنُ هذا أن مستنداً فارسيّاً حقيقيّاً يُسطَّح إلى العربية. والمنصّة سعوديّةٌ
 * قانونيّة، والحرفان يُرسمان متطابقين تقريباً، فالخسارةُ لا تكاد تُرى والمكسبُ
 * كلُّ بحثٍ في المنصّة.
 *
 * و`ى` (الألف المقصورة) ليست منه: عربيّةٌ أصيلة في «على» و«إلى» و«مؤدّى» —
 * ثمانيَ عشرةَ مرّة في المستند — فلا تُمسّ.
 */
const MISENCODED: Record<string, string> = {
  '\u06CC': '\u064A', // ی → ي
  '\u06BE': '\u0647', // ھ → ه
  '\u06A9': '\u0643', // ک → ك
  '\u06C1': '\u0647', // ہ → ه
};

/** يُقرأ محلّياً أم لا. الصور تحتاج قراءةً بصرية، وهي عمل النموذج لا المكتبة. */
export function readableLocally(file: File): boolean {
  const ext = (file.name.split('.').pop() ?? '').toLowerCase();
  return file.type === 'application/pdf' || ext === 'pdf';
}

/**
 * يستخرج نصّ ملفّ PDF، أو يردّ `null` إن لم يُخرج شيئاً يُعتدّ به.
 *
 * و`null` ليست خطأً: هي «لا نصّ في هذا الملف» — ممسوحٌ ضوئياً أو صُوَريّ —
 * والخادم يتولّاه بعدها. فلا يُوقف الرفع ولا يُعرض للقارئ خطأ.
 *
 * **ونقصٌ معروفٌ يُقال:** القوسُ قد يخرج منكوساً — «‏)٨٠٠٠(» مكان «(٨٠٠٠)» —
 * في مستنداتِ مُخرِجٍ يحفظ رمزَ القوس كما رُسم لا كما كُتب. وقُيس مُخرِجان
 * يتعاكسان في هذا، فلا يُميَّز أحدُهما من الآخر بالمحرف وحده؛ وقلبُه على
 * الظنّ يُفسد الصحيحَ ليصلح المعطوب. فتُترك الأقواسُ كما رُمِّزت: المعنى
 * كاملٌ، والخللُ في الشكل وحده.
 */
export async function extractPdfText(file: File): Promise<string | null> {
  try {
    // تحميلٌ عند الطلب: قطعةٌ منفصلة لا تدخل حزمة الصفحة الأولى.
    const mupdf = await import('mupdf');
    const buf = new Uint8Array(await file.arrayBuffer());
    const doc = mupdf.Document.openDocument(buf, 'application/pdf');
    const pageCount = Math.min(doc.countPages(), MAX_PAGES);

    const pages: string[][] = [];
    let anyArabic = false;
    const raw: Unit[][][] = [];

    for (let p = 0; p < pageCount; p++) {
      const st = doc.loadPage(p).toStructuredText('preserve-whitespace');

      /* **التجميع بالسطر البصريّ لا بكتل المكتبة.** المكتبة تقطع السطر عند كل
         تحوّل اتجاه — قِيس على مستندٍ حقيقيّ: ثمانيةُ أسطر من تسعةٍ وعشرين
         قُطّعت، وواحدٌ منها إلى أربع كتل. فتخرج الجملةُ الواحدة خمسةَ أسطر
         ورقمُها معزولٌ عن جملته.

         **ولا يُقطع السطر بالإحداثيّ المجرَّد أيضاً.** بعض المُخرِجات تُنزل
         الشدّةَ وحرفَها معاً على خطِّ أساسٍ يخالف السطر بأجزاء من النقطة: قِيس
         سطرٌ عند 122.25 وفيه «مّ» عند 124.30 و«ّن» عند 123.13 و«ًا» عند 119.61.
         فتقريبُ الإحداثيّ إلى درجةٍ ثابتة يقذف الحرفَ وشدّتَه إلى سطرٍ وحدهما،
         فتخرج «ولمّا» ثلاثَ قطع.

         فالسطرُ عنقودٌ لا قيمة: تُجمع الإحداثيّات المتقاربة معاً، وحدُّ التقارب
         نصفُ قامة الخطّ — والفجوةُ بين سطرين حقيقيَّين لا تقلّ عن قامةٍ كاملة،
         فلا يلتبس العنقودان. */
      /* المرحلةُ الأولى: تُجمع المحارف كما وردت، بمواضعها وقاماتها، بلا حكم.
         والحكمُ يحتاج نظراً إلى ما بعدُ — انظر المرحلة الثانية — والمشيُ مع
         المكتبة لا يرى إلّا ما مضى. */
      interface Raw { c: string; span: [number, number] | null; x: number; y: number; size: number; zero: boolean; block: number }
      const items: Raw[] = [];
      let block = 0;
      st.walk({
        beginLine() { block++; },
        onChar(c: string, origin: any, _font: unknown, size: number, quad: unknown) {
          if (!anyArabic && ARABIC.test(c)) anyArabic = true;
          const a = Array.isArray(origin) ? origin : [origin?.x ?? 0, origin?.y ?? 0];
          const span = quadSpan(quad);
          items.push({ c, span, x: span ? span[0] : a[0], y: a[1], size: size || 0, zero: isZeroWidth(span, c), block });
        },
      });

      /* المرحلةُ الثانية: تُنسَب كلُّ تتمّةٍ إلى رسمها.
         والمواضعُ وحدها تلتبس: ألفُ «لا» في «ريال لا» تقع على أصل الفراغ قبلها
         **وعلى** الحافّة اليمنى للامها بعدها في آنٍ واحد. فلا يُحسم إلّا
         بالنظر إلى الجهتين معاً، وترتيبُ القواعد هو الحكم. */
      const nextReal: number[] = new Array(items.length).fill(-1);
      for (let k = items.length - 1, seen = -1; k >= 0; k--) { nextReal[k] = seen; if (!items[k].zero) seen = k; }

      const marks: { u: Unit; y: number }[] = [];
      const sizeAt = new Map<number, number>();
      let last: Unit | null = null;
      let lastSpan: [number, number] | null = null;
      let lastBlank = false;
      let lastBlock = -1;
      /* تتمّاتٌ تنتظر رسمَها التالي — وتُقلَب، لأن المقطع المعكوس يُصدرها بعكس
         منطقها: «الله» تُصدَر `ه` ثم `ل` ثم `ل` ثم ألفُها. */
      let held: string[] = [];

      for (let k = 0; k < items.length; k++) {
        const it = items[k];
        // ولا يعبر رسمٌ حدَّ كتلة.
        if (it.block !== lastBlock) { last = null; lastSpan = null; held = []; lastBlock = it.block; }

        if (!it.zero) {
          const fresh: Unit = { s: it.c + held.join(''), x: it.x };
          held = [];
          last = fresh;
          lastSpan = it.span;
          lastBlank = it.c.trim() === '';
          marks.push({ u: fresh, y: it.y });
          sizeAt.set(it.y, Math.max(sizeAt.get(it.y) ?? 0, it.size));
          continue;
        }

        // ١ — على الحافّة اليمنى لرسمٍ سبقها: تلحق به كما وردت. «لا» في الوورد.
        if (last && lastSpan && Math.abs(it.x - lastSpan[1]) < EPS) { last.s += it.c; continue; }

        /* ٢ — على الحافّة اليمنى لرسمٍ يليها: هي له، وقد سبقته في الإصدار.
           وتقديمُ هذه القاعدة على الثالثة هو ما يُبقي الفراغ في «ريال لا». */
        const n = nextReal[k];
        if (n >= 0 && items[n].block === it.block && items[n].span && Math.abs(it.x - items[n].span![1]) < EPS) {
          held.unshift(it.c);
          continue;
        }

        /* ٣ — على أصل فراغٍ يحمل عرضَ الرسم: حاملُ حركةٍ مقلوب. «مّ» و«اً».
           ولا يحمل الفراغُ حركةً في نصٍّ سليم، فالفراغُ وحده يأذن بهذا. */
        if (last && lastSpan && lastBlank && Math.abs(it.x - lastSpan[0]) < EPS) { last.s = it.c + last.s; continue; }

        // ٤ — وما لم يُعرف صاحبُه: يلحق بالسابق، ولا يُطرح محرفٌ من النصّ.
        if (last) last.s += it.c; else held.unshift(it.c);
      }

      /* العنقدة: تُرتَّب الإحداثيّات، ثم يُفتح عنقودٌ جديد كلّما جاوزت الفجوةُ
         الحدَّ. والحدُّ من قامة الخطّ عند الطرفين لا من رقمٍ مكتوب، فمستندٌ
         بخطٍّ كبير ومستندٌ بخطٍّ صغير يُقاسان بمسطرتهما. */
      const ys = [...new Set(marks.map((m) => m.y))].sort((a, b) => a - b);
      const anchorOf = new Map<number, number>();
      let anchor = ys[0] ?? 0;
      for (let k = 0; k < ys.length; k++) {
        if (k > 0) {
          const tol = Math.max(sizeAt.get(ys[k]) ?? 0, sizeAt.get(ys[k - 1]) ?? 0) / 2;
          if (ys[k] - ys[k - 1] > tol) anchor = ys[k];
        }
        anchorOf.set(ys[k], anchor);
      }
      const rows = new Map<number, Unit[]>();
      for (const m of marks) {
        const key = anchorOf.get(m.y) ?? m.y;
        const row = rows.get(key) ?? [];
        row.push(m.u);
        rows.set(key, row);
      }
      /* رسمٌ واحد لا يحمل فراغاً. فإن ظهر فراغٌ داخل وحدةٍ ذاتِ حروف فهو من
         جدول الخطّ لا من النصّ — حاملُ «مّ» فراغٌ يحمل عرضَ الميم — وتركُه
         يشقّ الكلمة: «ولمّ ا» مكان «ولمّا». */
      for (const r of rows.values()) {
        for (const u of r) if (u.s.length > 1) u.s = u.s.replace(/\s+/g, '');
      }
      const lines = [...rows.entries()].sort((a, b) => a[0] - b[0]).map(([, r]) => r);
      raw.push(lines);
    }

    /* اتجاهُ المستند لا اتجاهُ السطر.
       سطرٌ إنجليزيّ داخل فقرةٍ عربية تقع علامتُه الأخيرة يساراً بحكم اتجاه
       الفقرة، فقراءتُه من اليسار تُخرج «‏.English sentence» بنقطةٍ في أوّله،
       وقراءتُه باتجاه المستند تردّ النقطةَ إلى آخره. وقياسُه بالسطر وحده جُرّب
       فأصلح فقرةً إنجليزيةً قائمةً بذاتها وأفسد هذه، وهذه أكثرُ في مستنداتنا.
       **ويبقى نقصاً معلوماً:** فقرةٌ إنجليزية محاذاةُ سطورها من اليسار داخل
       مستندٍ عربيّ يُعكس ترتيبُ كلماتها. */
    for (const lines of raw) {
      pages.push(lines.map((l) => toLogical(l, anyArabic).replace(/\s+/g, ' ').trim()).filter(Boolean));
    }

    /* التوحيد إلى NFC: بعض الخطوط تُخرج الهمزة حرفاً مركَّباً، فتصير الكلمة
       الواحدة صورتين لا تتطابقان في بحثٍ ولا مقارنة. */
    const text = pages
      .map((l) => l.join('\n'))
      .join('\n\n')
      .replace(/\n{3,}/g, '\n\n')
      .replace(/[\u06CC\u06BE\u06A9\u06C1]/g, (c) => MISENCODED[c])
      .normalize('NFC')
      .trim();

    /* عتبةٌ لا صفر: صفحةٌ ممسوحة ضوئياً قد تحمل رقم صفحةٍ أو ترويسةً في طبقة
       نصّ، فتخرج بضعةُ محارف تُوهم أن الملف قُرئ — ثم لا يجد المساعد شيئاً.
       فما دون العتبة يُعدّ لا نصّ، ويُترك للخادم يقرأه بصرياً. */
    return text.length >= 40 ? text : null;
  } catch {
    // مكتبةٌ لم تُحمَّل، أو ملفٌّ معطوب، أو ذاكرةٌ ضاقت: يُرفع الملف ويتولّاه
    // الخادم. والرفع لا يتوقّف لأجل تحسينٍ في الكلفة.
    return null;
  }
}
