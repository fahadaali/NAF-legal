/* ============================================================
   «من ‹الأداة›» — علامةُ ما بدأ أو حُفظ من أداة ذكاءٍ اصطناعي مربوطة.

   موضعٌ واحد لثلاثة مواضع: قائمة المحادثات، وترويسة المحادثة، والرسالة
   التي حفظتها الأداة (naf-terms.md §١٥ — «مصدر المحادثة»). كانت النسخُ
   الثلاث مكتوبةً كلٌّ في موضعه، فتعديلُ اللفظ أو الأيقونة يلزمه ثلاثة
   تعديلات — وهو الانحراف الذي يمنعه CLAUDE.md وهو يبدأ.

   `Plug` من naf-icons.md، أيقونةٌ ونصّ لا لونٌ وحده. واسمُ الأداة بياناتٌ
   معزولة بـ`bdi`، والمجهولُ منه «أداة مربوطة» المسجّلة.
   ============================================================ */

import { Icon, ICON_SM } from '../lib/icons';

export default function OriginTag({ client, className = '' }: { client: string | null; className?: string }) {
  return (
    <span className={`conv-origin${className ? ` ${className}` : ''}`}>
      <Icon.aiTool size={ICON_SM} aria-hidden /> من {client ? <bdi>{client}</bdi> : 'أداة مربوطة'}
    </span>
  );
}
